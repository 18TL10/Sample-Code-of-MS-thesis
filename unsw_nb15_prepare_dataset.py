#Helpers
def label_counts(y):
    values, counts = np.unique(np.asarray(y).ravel(), return_counts=True)
    return {str(int(v)): int(c) for v, c in zip(values, counts)}


def find_constant_columns(X_train_df):
    """Identify constant columns using TRAINING DATA ONLY."""
    return [
        col for col in X_train_df.columns
        if X_train_df[col].nunique(dropna=False) <= 1
    ]


def correlation_filter_from_train(X_train_df, threshold):
    """
    Remove redundant features using feature-feature Pearson correlatio.
    """
    corr_matrix = X_train_df.corr(numeric_only=True).abs()

    cols_to_drop = set()
    log = []

    columns = list(corr_matrix.columns)
    for i in range(len(columns)):
        for j in range(i):
            value = corr_matrix.iloc[i, j]
            if pd.notna(value) and value > threshold:
                col_to_drop = columns[i]
                cols_to_drop.add(col_to_drop)
                log.append(
                    f"{columns[i]} -> {columns[j]} == {float(value):.8f}"
                )
                break

    selected_columns = [c for c in X_train_df.columns if c not in cols_to_drop]
    return selected_columns, log


def save_txt_lines(path, lines):
    with open(path, "w", encoding="utf-8") as f:
        for line in lines:
            f.write(str(line) + "\n")


def save_mat_splits(output_dir, X_train, y_train, X_test, y_test):
    """Save train/validation/test matrices with consistent variable names."""
    sio.savemat(
        os.path.join(output_dir, "FeatLabs_Train_Binary.mat"),
        {
            "Feats_Train": np.asarray(X_train, dtype=np.float32),
            "Labs_Train": np.asarray(y_train, dtype=np.int8),
        },
    )
    sio.savemat(
        os.path.join(output_dir, "FeatLabs_Test_Binary.mat"),
        {
            "Feats_Test": np.asarray(X_test, dtype=np.float32),
            "Labs_Test": np.asarray(y_test, dtype=np.int8),
        },
    )


def save_experiment_metadata(
    output_dir,
    method_name,
    original_feature_names,
    selected_feature_names,
    y_train,
    y_test,
    transformed_dim,
    extra=None,
):
    metadata = {
        "method": method_name,
        "original_feature_count": len(original_feature_names),
        "selected_input_feature_count": len(selected_feature_names),
        "transformed_feature_count": int(transformed_dim),
        "original_feature_names": list(original_feature_names),
        "selected_input_feature_names": list(selected_feature_names),
        "train_label_counts": label_counts(y_train),
        "test_label_counts": label_counts(y_test),
        "random_state": RANDOM_STATE,
        "test_size": TEST_SIZE,
    }
    if extra:
        metadata.update(extra)

    with open(
        os.path.join(output_dir, "preprocessing_metadata.json"),
        "w",
        encoding="utf-8",
    ) as f:
        json.dump(metadata, f, indent=2)


def prepare_scaled_dataset(
    method_name,
    output_dir,
    X_train_df,
    X_test_df,
    y_train,
    y_test,
    selected_columns,
    correlation_log=None,
):
    """
    Scale a selected feature subset. Scaler is fitted on TRAINING DATA ONLY.
    """
    scaler = StandardScaler()

    X_train = scaler.fit_transform(X_train_df[selected_columns]).astype(np.float32)
    X_test = scaler.transform(X_test_df[selected_columns]).astype(np.float32)

    save_mat_splits(
        output_dir,
        X_train, y_train,
        X_test, y_test,
    )

    preprocessing = {
        "method": method_name,
        "selected_feature_names": list(selected_columns),
        "scaler": scaler,
        "pca": None,
    }
    joblib.dump(
        preprocessing,
        os.path.join(output_dir, "preprocessing.joblib"),
    )

    if correlation_log is not None:
        save_txt_lines(
            os.path.join(output_dir, "correlation_filter_log.txt"),
            correlation_log,
        )

    save_experiment_metadata(
        output_dir=output_dir,
        method_name=method_name,
        original_feature_names=X_train_df.columns.tolist(),
        selected_feature_names=selected_columns,
        y_train=y_train,
        y_test=y_test,
        transformed_dim=X_train.shape[1],
        extra={
            "preprocessing_sequence": "selected columns -> StandardScaler",
        },
    )

    print(
        f"{method_name}: "
        f"{len(X_train_df.columns)} input features -> {X_train.shape[1]} model features"
    )


    del X_train, X_test
    gc.collect()


def prepare_pca_dataset(
    method_name,
    output_dir,
    X_train_df,
    X_test_df,
    y_train,
    y_test,
    selected_columns,
    explained_variance,
):
    """
    Fit StandardScaler and PCA on TRAINING DATA ONLY, then transform
    validation and test data with the fitted objects.
    """
    scaler = StandardScaler()

    X_train_scaled = scaler.fit_transform(X_train_df[selected_columns])
    X_test_scaled = scaler.transform(X_test_df[selected_columns])

    pca = PCA(
        n_components=explained_variance,
        svd_solver="full",
    )

    X_train = pca.fit_transform(X_train_scaled).astype(np.float32)
    X_test = pca.transform(X_test_scaled).astype(np.float32)

    # MEMORY FIX: the scaled float64 matrices are only needed to fit/transform
    # PCA; free them as soon as PCA has consumed them.
    del X_train_scaled, X_test_scaled
    gc.collect()

    save_mat_splits(
        output_dir,
        X_train, y_train,
        X_test, y_test,
    )

    preprocessing = {
        "method": method_name,
        "selected_feature_names": list(selected_columns),
        "scaler": scaler,
        "pca": pca,
    }
    joblib.dump(
        preprocessing,
        os.path.join(output_dir, "preprocessing.joblib"),
    )

    save_experiment_metadata(
        output_dir=output_dir,
        method_name=method_name,
        original_feature_names=X_train_df.columns.tolist(),
        selected_feature_names=selected_columns,
        y_train=y_train,
        y_test=y_test,
        transformed_dim=X_train.shape[1],
        extra={
            "preprocessing_sequence": "selected columns -> StandardScaler -> PCA",
            "pca_target_explained_variance": explained_variance,
            "pca_actual_explained_variance": float(
                np.sum(pca.explained_variance_ratio_)
            ),
            "pca_components": int(pca.n_components_),
        },
    )

    print(
        f"{method_name}: "
        f"{len(selected_columns)} scaled features -> {X_train.shape[1]} PCA components "
        f"(explained variance={np.sum(pca.explained_variance_ratio_):.6f})"
    )

    del X_train, X_test
    gc.collect()

