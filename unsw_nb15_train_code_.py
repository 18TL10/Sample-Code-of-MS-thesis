#Reproducibility helper
def set_all_seeds(seed=SEED):
    random.seed(seed)
    np.random.seed(seed)
    tf.keras.utils.set_random_seed(seed)

    # Best-effort deterministic TensorFlow operations.
    try:
        tf.config.experimental.enable_op_determinism()
    except Exception:
        pass

# Plot helper
def plot_history(history, file_to_save, experiment_name):
    f1_values = history.history["f1_score"]
    loss_values = history.history["loss"]
    epochs = range(1, len(f1_values) + 1)

    fig, axes = plt.subplots(
        nrows=2,
        ncols=1,
        figsize=(7, 7),
        constrained_layout=True,
    )

    axes[0].plot(epochs, f1_values, "--", label="Training macro-F1")
    axes[0].set_title(experiment_name + " - Training macro-F1")
    axes[0].set_xlabel("Epoch")
    axes[0].set_ylabel("Macro-F1")
    axes[0].legend()
    axes[0].grid()

    axes[1].plot(epochs, loss_values, "--", label="Training loss")
    axes[1].set_title(experiment_name + " - Training loss")
    axes[1].set_xlabel("Epoch")
    axes[1].set_ylabel("Loss")
    axes[1].legend()
    axes[1].grid()

    plt.savefig(file_to_save, dpi=600, bbox_inches="tight")
    plt.show()
    plt.close(fig)

# Model definition
def create_fcnn_64_32_16(num_features, num_classes=NUM_CLASSES):
    model = Sequential([
        Input(shape=(num_features,)),
        Dense(64, activation="relu"),
        Dropout(0.3),
        Dense(32, activation="relu"),
        Dropout(0.3),
        Dense(16, activation="relu"),
        Dropout(0.2),
        Dense(num_classes),
        Activation("softmax"),
    ])
    return model

# Data loader
def load_experiment_data(dataset_dir):
    train_file = os.path.join(dataset_dir, "FeatLabs_Train_Binary.mat")
    test_file = os.path.join(dataset_dir, "FeatLabs_Test_Binary.mat")

    for path in [train_file, test_file]:
        if not os.path.exists(path):
            raise FileNotFoundError("Required dataset file not found: " + path)

    train_mat = sio.loadmat(train_file)
    test_mat = sio.loadmat(test_file)

    X_train = train_mat["Feats_Train"].astype(np.float32)
    y_train = train_mat["Labs_Train"].ravel().astype(np.int8)

    X_test = test_mat["Feats_Test"].astype(np.float32)
    y_test = test_mat["Labs_Test"].ravel().astype(np.int8)

    del train_mat, test_mat

    for name, labels in [
        ("train", y_train),
        ("test", y_test),
    ]:
        unique = set(np.unique(labels).tolist())
        if not unique.issubset({0, 1}):
            raise ValueError(f"Unexpected labels in {name}: {sorted(unique)}")

    if X_train.shape[1] != X_test.shape[1]:
        raise ValueError("Feature dimensions differ across train/test.")

    return X_train, y_train, X_test, y_test

# Train one experiment
def train_binary_experiment(experiment_name, dataset_dir):
    print("\n" + "=" * 80)
    print("EXPERIMENT:", experiment_name)
    print("=" * 80)

    tf.keras.backend.clear_session()
    set_all_seeds(SEED)

    (
        X_train,
        y_train,
        X_test,
        y_test,
    ) = load_experiment_data(dataset_dir)

    print("Training   :", X_train.shape, np.unique(y_train, return_counts=True))
    print("Testing    :", X_test.shape, np.unique(y_test, return_counts=True))

    num_features = X_train.shape[1]

    y_train_cat = to_categorical(y_train, num_classes=NUM_CLASSES)

    counts = np.bincount(y_train, minlength=NUM_CLASSES)
    total = counts.sum()

    class_weight = {
        i: total / (NUM_CLASSES * counts[i])
        for i in range(NUM_CLASSES)
        if counts[i] > 0
    }

    print("Class weights:", class_weight)

    model = create_fcnn_64_32_16(
        num_features=num_features,
        num_classes=NUM_CLASSES,
    )

    output_dir = os.path.join(
        MODELS_ROOT,
        experiment_name + "-Binary",
    )
    os.makedirs(output_dir, exist_ok=True)

    history_excel = os.path.join(
        output_dir,
        experiment_name + "-Binary-History.xlsx",
    )
    history_plot = os.path.join(
        output_dir,
        experiment_name + "-Binary-History.png",
    )

    # One unambiguous model file selected ONLY by training macro-F1.
    best_model_path = os.path.join(
        output_dir,
        "Best.keras",
    )

    checkpoint = ModelCheckpoint(
        best_model_path,
        monitor="f1_score",
        verbose=1,
        save_best_only=True,
        save_weights_only=False,
        mode="max",
    )

    early_stop = EarlyStopping(
        monitor="f1_score",
        mode="max",
        patience=5,
        restore_best_weights=True,
        verbose=1,
    )

    reduce_lr = ReduceLROnPlateau(
        monitor="loss",
        factor=0.2,
        patience=3,
        min_lr=0.0001,
        verbose=1,
    )

    model.compile(
        loss=CategoricalCrossentropy(),
        optimizer=Adam(learning_rate=LEARNING_RATE),
        metrics=[F1Score(average="macro", name="f1_score")],
    )

    model.summary()

    history = model.fit(
        X_train,
        y_train_cat,
        batch_size=BATCH_SIZE,
        epochs=NUM_EPOCHS,
        class_weight=class_weight,
        verbose=1,
        callbacks=[
            checkpoint,
            early_stop,
            reduce_lr,
        ],
        shuffle=True,
    )

    # Save complete training history.
    history_df = pd.DataFrame({
        "Train f1_score": history.history["f1_score"],
        "Train loss": history.history["loss"],
        "Learning rate": history.history.get(
            "learning_rate",
            [np.nan] * len(history.history["loss"]),
        ),
    })
    history_df.to_excel(history_excel, index=False)

    plot_history(
        history,
        history_plot,
        experiment_name,
    )

    # Reload the checkpoint explicitly. This is the model selected on training
    # performance and is the ONLY model used for final test evaluation.
    best_model = load_model(
        best_model_path,
        custom_objects={"F1Score": F1Score},
        compile=False,
    )

    test_scores = best_model.predict(
        X_test,
        batch_size=BATCH_SIZE,
        verbose=0,
    )
    test_pred = np.argmax(test_scores, axis=1)

    test_macro_f1 = f1_score(
        y_test,
        test_pred,
        average="macro",
    )

    best_train_f1 = float(np.max(history.history["f1_score"]))
    best_epoch = int(np.argmax(history.history["f1_score"]) + 1)

    print("\nBest training epoch:", best_epoch)
    print("Best training macro-F1:", best_train_f1)
    print("FINAL untouched-test macro-F1:", test_macro_f1)

    result = {
        "Experiment": experiment_name,
        "Features": num_features,
        "Best Epoch": best_epoch,
        "Best Training F1": best_train_f1,
        "Final Test F1": float(test_macro_f1),
        "Parameters": int(best_model.count_params()),
        "Best Model": best_model_path,
    }

    del (
        X_train, y_train,
        X_test, y_test,
        y_train_cat,
        model, best_model,
        test_scores, test_pred,
    )
    gc.collect()

    return result

