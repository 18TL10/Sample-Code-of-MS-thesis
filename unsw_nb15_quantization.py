# Helpers
import time # Added for retry mechanism

def load_binary_data(dataset_folder):
    train_file = os.path.join(
        dataset_folder,
        "FeatLabs_Train_Binary.mat",
    )
    test_file = os.path.join(
        dataset_folder,
        "FeatLabs_Test_Binary.mat",
    )

    train_mat = sio.loadmat(train_file)
    test_mat = sio.loadmat(test_file)

    X_train = train_mat["Feats_Train"].astype(np.float32)
    y_train = train_mat["Labs_Train"].ravel().astype(np.int8)

    X_test = test_mat["Feats_Test"].astype(np.float32)
    y_test = test_mat["Labs_Test"].ravel().astype(np.int8)

    for name, labels in [("train", y_train), ("test", y_test)]:
        unique = set(np.unique(labels).tolist())
        if not unique.issubset({0, 1}):
            raise ValueError(f"Unexpected {name} labels: {sorted(unique)}")

    return X_train, y_train, X_test, y_test


def make_representative_indices(y_train, max_samples, seed):
    """
    Select a stratified representative subset from TRAINING DATA ONLY.
    """
    y_train = np.asarray(y_train).ravel()
    n_total = len(y_train)
    n_rep = min(max_samples, n_total)

    if n_rep == n_total:
        return np.arange(n_total)

    splitter = StratifiedShuffleSplit(
        n_splits=1,
        train_size=n_rep,
        random_state=seed,
    )
    rep_idx, _ = next(
        splitter.split(
            np.zeros((n_total, 1)),
            y_train,
        )
    )
    return rep_idx


def convert_tflite_float32(model, output_file):
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    tflite_model = converter.convert()

    os.makedirs(os.path.dirname(output_file), exist_ok=True) # Ensure directory exists
    for attempt in range(3):
        try:
            with open(output_file, "wb") as f:
                f.write(tflite_model)
            break # If successful, break the loop
        except FileNotFoundError as e:
            if attempt < 2:
                print(f"FileNotFoundError encountered for {output_file}. Retrying in 1 second... (Attempt {attempt + 1})")
                time.sleep(1)
            else:
                raise # Re-raise after all attempts fail

    return os.path.getsize(output_file) / 1024.0


def convert_tflite_float16(model, output_file):
    """
    Standard TFLite FP16 post-training quantization.
    Weights are stored at FP16 precision; runtime arithmetic can depend on the
    target delegate/device.
    """
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.target_spec.supported_types = [tf.float16]

    tflite_model = converter.convert()

    os.makedirs(os.path.dirname(output_file), exist_ok=True) # Ensure directory exists
    for attempt in range(3):
        try:
            with open(output_file, "wb") as f:
                f.write(tflite_model)
            break # If successful, break the loop
        except FileNotFoundError as e:
            if attempt < 2:
                print(f"FileNotFoundError encountered for {output_file}. Retrying in 1 second... (Attempt {attempt + 1})")
                time.sleep(1)
            else:
                raise # Re-raise after all attempts fail

    return os.path.getsize(output_file) / 1024.0


def convert_tflite_int8(
    model,
    output_file,
    X_train,
    y_train,
    seed=SEED,
):
    """
    Full-integer INT8 conversion.

    Calibration samples are selected only from the training partition.
    TFLITE_BUILTINS_INT8 prevents a silent float-op fallback.
    """
    rep_idx = make_representative_indices(
        y_train,
        max_samples=REPRESENTATIVE_SAMPLES,
        seed=seed,
    )

    def representative_dataset():
        for i in rep_idx:
            yield [X_train[i:i + 1].astype(np.float32)]

    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = representative_dataset
    converter.target_spec.supported_ops = [
        tf.lite.OpsSet.TFLITE_BUILTINS_INT8
    ]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8

    tflite_model = converter.convert()

    os.makedirs(os.path.dirname(output_file), exist_ok=True) # Ensure directory exists
    for attempt in range(3):
        try:
            with open(output_file, "wb") as f:
                f.write(tflite_model)
            break # If successful, break the loop
        except FileNotFoundError as e:
            if attempt < 2:
                print(f"FileNotFoundError encountered for {output_file}. Retrying in 1 second... (Attempt {attempt + 1})")
                time.sleep(1)
            else:
                raise # Re-raise after all attempts fail

    return os.path.getsize(output_file) / 1024.0, len(rep_idx)


def quantize_input(x, details):
    dtype = details["dtype"]

    if dtype in (np.int8, np.uint8):
        scale, zero_point = details["quantization"]

        if scale == 0:
            raise ValueError(
                "Quantized input tensor has scale=0; cannot quantize input."
            )

        qmin = np.iinfo(dtype).min
        qmax = np.iinfo(dtype).max

        x = np.round(x / scale + zero_point)
        x = np.clip(x, qmin, qmax)

    return x.astype(dtype)


def dequantize_output(y, details):
    dtype = details["dtype"]

    if dtype in (np.int8, np.uint8):
        scale, zero_point = details["quantization"]

        if scale == 0:
            raise ValueError(
                "Quantized output tensor has scale=0; cannot dequantize output."
            )

        return (
            y.astype(np.float32) - zero_point
        ) * scale

    return y.astype(np.float32)


def evaluate_tflite(
    model_file,
    X_test,
    y_test,
    batch_size=TFLITE_BATCH_SIZE,
    return_scores=False,
):
    interpreter = tf.lite.Interpreter(model_path=model_file)

    input_details = interpreter.get_input_details()[0]
    output_details = interpreter.get_output_details()[0]

    n_features = X_test.shape[1]

    # Attempt batched inference. Fall back to batch size 1 if necessary.
    try:
        interpreter.resize_tensor_input(
            input_details["index"],
            [batch_size, n_features],
            strict=False,
        )
        interpreter.allocate_tensors()
        step = batch_size
    except (ValueError, RuntimeError):
        interpreter.allocate_tensors()
        step = 1

    input_details = interpreter.get_input_details()[0]
    output_details = interpreter.get_output_details()[0]

    scores = []

    for start in range(0, X_test.shape[0], step):
        chunk = X_test[start:start + step].astype(np.float32)

        if chunk.shape[0] != step:
            interpreter.resize_tensor_input(
                input_details["index"],
                list(chunk.shape),
                strict=False,
            )
            interpreter.allocate_tensors()

            input_details = interpreter.get_input_details()[0]
            output_details = interpreter.get_output_details()[0]

        interpreter.set_tensor(
            input_details["index"],
            quantize_input(chunk, input_details),
        )
        interpreter.invoke()

        output = interpreter.get_tensor(
            output_details["index"]
        )
        scores.append(
            dequantize_output(output, output_details)
        )

    scores = np.concatenate(scores, axis=0)

    # Current DNN has two softmax outputs, so class prediction is argmax.
    if scores.ndim != 2 or scores.shape[1] != 2:
        raise ValueError(
            f"Expected an N x 2 softmax output, got {scores.shape}"
        )

    predictions = np.argmax(scores, axis=1)

    macro_f1 = f1_score(
        y_test,
        predictions,
        average="macro",
    )

    if return_scores:
        return macro_f1, scores, predictions
    return macro_f1


def evaluate_keras(model, X_test, y_test):
    scores = model.predict(
        X_test,
        batch_size=KERAS_PREDICT_BATCH_SIZE,
        verbose=0,
    )
    predictions = np.argmax(scores, axis=1)

    macro_f1 = f1_score(
        y_test,
        predictions,
        average="macro",
    )

    return macro_f1, scores, predictions

